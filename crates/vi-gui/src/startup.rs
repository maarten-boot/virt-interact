//! Start-up decisions before the main window (SPEC-004): what the command
//! line asks for, how a message is shown, and the window icon.
//!
//! A Windows release build has no console (GUI subsystem), so `--help`,
//! `--version` and start-up errors are shown in a small window there
//! (crosscheck 2026-11-14-03, C1). Everywhere else they go to the terminal.

use std::path::PathBuf;

use eframe::egui;
use vi_core::contrast::Palette;
use vi_core::paths::{self, CliArgs};

use crate::theme;

/// What `main` does after reading the command line.
#[derive(Debug, Clone, PartialEq)]
pub enum Start {
    /// Start the app with this config file.
    Run(PathBuf),
    /// Show `text` and exit with `code` (0: help/version, 2: usage error).
    Exit { text: String, code: i32 },
}

/// Decide from the arguments (without the program name).
pub fn start<I, S>(args: I) -> Start
where
    I: IntoIterator<Item = S>,
    S: Into<String>,
{
    let args = match CliArgs::parse(args) {
        Ok(a) => a,
        Err(e) => {
            return Start::Exit {
                text: format!("{e}\n\n{}", paths::USAGE),
                code: 2,
            };
        }
    };
    if args.show_help {
        return Start::Exit {
            text: paths::USAGE.to_string(),
            code: 0,
        };
    }
    if args.show_version {
        return Start::Exit {
            text: format!("{} {}", vi_core::APP_NAME, vi_core::VERSION),
            code: 0,
        };
    }
    from_config_path(args.config_path())
}

/// `Run` with the path, or the error when no config directory is known.
pub fn from_config_path(path: Option<PathBuf>) -> Start {
    match path {
        Some(p) => Start::Run(p),
        None => Start::Exit {
            text: "Cannot determine the config directory; use --config <PATH>.".into(),
            code: 2,
        },
    }
}

/// Whether messages go to a window instead of the terminal: Windows
/// release builds, which have no console.
pub const MESSAGES_IN_WINDOW: bool = cfg!(all(windows, not(debug_assertions)));

/// Show `text` (terminal or window, see [`MESSAGES_IN_WINDOW`]) and exit.
pub fn exit_with(text: &str, code: i32) -> ! {
    if MESSAGES_IN_WINDOW {
        let _ = message_window(text);
    } else if code == 0 {
        println!("{text}");
    } else {
        eprintln!("{text}");
    }
    std::process::exit(code)
}

/// A small window with `text` and an OK button, in the default palette
/// (the config is not read yet).
pub fn message_window(text: &str) -> eframe::Result {
    let text = text.to_string();
    let options = eframe::NativeOptions {
        viewport: viewport()
            .with_inner_size([640.0, 320.0])
            .with_resizable(true),
        ..Default::default()
    };
    let palette = Palette::default_palette();
    let mut themed = false;
    eframe::run_ui_native(vi_core::APP_NAME, options, move |ui, _frame| {
        if !themed {
            theme::apply(ui.ctx(), &palette);
            themed = true;
        }
        egui::CentralPanel::default().show(ui, |ui| {
            if message_ui(ui, &text) {
                ui.ctx().send_viewport_cmd(egui::ViewportCommand::Close);
            }
        });
    })
}

/// The message window's content; true when OK was clicked (or Enter or
/// Escape pressed).
pub fn message_ui(ui: &mut egui::Ui, text: &str) -> bool {
    let mut done =
        ui.input(|i| i.key_pressed(egui::Key::Enter) || i.key_pressed(egui::Key::Escape));
    egui::Panel::bottom("ok").show(ui, |ui| {
        ui.add_space(4.0);
        done |= ui.button("OK").clicked();
        ui.add_space(4.0);
    });
    egui::ScrollArea::both()
        .auto_shrink([false, false])
        .show(ui, |ui| {
            // Usage text keeps its columns: no wrapping, it scrolls instead.
            ui.add(egui::Label::new(egui::RichText::new(text).monospace()).extend());
        });
    done
}

/// The app icon, 256 px (generated by `scripts/make_icon.py`).
pub const ICON_PNG: &[u8] = include_bytes!("../../../packaging/icon/virt-interact-256.png");

/// Viewport settings shared by every window: title, icon and the app id
/// that Wayland and X11 desktops match with `virt-interact.desktop`.
pub fn viewport() -> egui::ViewportBuilder {
    let mut v = egui::ViewportBuilder::default()
        .with_title(vi_core::APP_NAME)
        .with_app_id(vi_core::APP_NAME);
    if let Ok(icon) = eframe::icon_data::from_png_bytes(ICON_PNG) {
        v = v.with_icon(icon);
    }
    v
}

#[cfg(test)]
mod tests {
    use super::*;

    // TC-026a: help, version and usage errors become a message and an exit
    // code; a --config path starts the app.
    #[test]
    fn start_decisions() {
        assert_eq!(
            start(["--config", "/x/c.toml"]),
            Start::Run("/x/c.toml".into())
        );
        let Start::Exit { text, code } = start(["--help"]) else {
            panic!()
        };
        assert_eq!((text.as_str(), code), (paths::USAGE, 0));
        let Start::Exit { text, code } = start(["-V"]) else {
            panic!()
        };
        assert_eq!(code, 0);
        assert!(text.starts_with(vi_core::APP_NAME), "{text}");
        let Start::Exit { text, code } = start(["--bogus"]) else {
            panic!()
        };
        assert_eq!(code, 2);
        assert!(
            text.contains("--bogus") && text.contains(paths::USAGE),
            "{text}"
        );
        let Start::Exit { code, .. } = from_config_path(None) else {
            panic!()
        };
        assert_eq!(code, 2);
    }

    // TC-026a: the message window renders headless and OK closes it.
    #[test]
    fn message_ui_renders_and_closes() {
        let ctx = egui::Context::default();
        theme::apply(&ctx, &Palette::default_palette());
        let mut done = false;
        let _ = ctx.run_ui(egui::RawInput::default(), |ui| {
            done = message_ui(ui, paths::USAGE);
        });
        assert!(!done);
        let input = egui::RawInput {
            events: vec![egui::Event::Key {
                key: egui::Key::Escape,
                physical_key: None,
                pressed: true,
                repeat: false,
                modifiers: Default::default(),
            }],
            ..Default::default()
        };
        let _ = ctx.run_ui(input, |ui| done = message_ui(ui, paths::USAGE));
        assert!(done);
    }

    // The embedded icon decodes (TC-122).
    #[test]
    fn icon_decodes() {
        let i = eframe::icon_data::from_png_bytes(ICON_PNG).unwrap();
        assert_eq!((i.width, i.height), (256, 256));
    }
}
